# Recomputes the trusted SHA-256 pin entries for `src/transcription/verify.rs`
# (`pinned()` and `pinned_repo_commit()`) after a DELIBERATE artifact update —
# a new runtime release, or a model repo bump. Print-and-compare only: it never
# edits source, so reviewing the diff of a pin change stays a human decision.
#
#   scripts/update-pins.sh                 # Qwen + GitHub runtimes (public)
#
# Requires: bash, curl, python3, sha256sum.
#
# The pinned commits are taken from the model repos' current main; when you
# accept a new commit, update BOTH the URLs in parakeet.rs/qwen.rs and
# `pinned_repo_commit()` — the download_urls_resolve_at_the_pinned_commit test
# and the build keep them honest.

set -euo pipefail
cd "$(dirname "$0")/.."

AUTH=()
if [ -n "${HF_TOKEN:-}" ]; then AUTH=(-H "Authorization: Bearer $HF_TOKEN"); fi

emit() { printf '        "%s" => {\n            Some("%s")\n        }\n' "$1" "$2"; }

hf_json() { curl -sf "${AUTH[@]}" "$1"; }

echo "    // ── generated by scripts/update-pins.sh ─────────────────────────"

for repo in "Qwen/Qwen3-ASR-0.6B" "Qwen/Qwen3-ASR-1.7B" "csukuangfj/sherpa-onnx-nemo-parakeet-tdt-0.6b-v3-int8"; do
    commit=$(hf_json "https://huggingface.co/api/models/$repo" | python3 -c 'import json,sys; print(json.load(sys.stdin)["sha"])')
    echo "    // $repo @ $commit"
    hf_json "https://huggingface.co/api/models/$repo/tree/$commit" |
        python3 -c '
import json, sys
for f in json.load(sys.stdin):
    if f.get("type") != "file":
        continue
    path = f["path"]
    if path in (".gitattributes", "README.md") or path.endswith(".py"):
        continue
    lfs = (f.get("lfs") or {}).get("oid")
    print("{}\t{}\t{}".format(path, lfs or "-", f.get("size", 0)))
' | while IFS=$'\t' read -r path lfs size; do
        if [[ "$lfs" =~ ^(sha256:)?[a-fA-F0-9]{64}$ ]]; then
            hash="${lfs#sha256:}"
        else
            # Small non-LFS files: hash the bytes directly.
            hash=$(curl -sfL "${AUTH[@]}" "https://huggingface.co/$repo/resolve/$commit/$path" | sha256sum | cut -d' ' -f1)
        fi
        emit "$repo/$path" "$hash"
    done
done

echo "    // ── GitHub release runtimes (assets can be re-uploaded; pin + provider digest) ──"
for spec in \
    "parakeet-runtime-v1.13.8-linux-x86_64 https://github.com/k2-fsa/sherpa-onnx/releases/download/v1.13.8/sherpa-onnx-v1.13.8-linux-x64-shared-no-tts.tar.bz2" \
    "qwen-runtime-v0.2.0-linux-x86_64 https://github.com/second-state/qwen3_asr_rs/releases/download/v0.2.0/asr-linux-x86_64.zip"; do
    key="${spec%% *}"; url="${spec#* }"
    hash=$(curl -sfL "$url" | sha256sum | cut -d' ' -f1)
    emit "$key" "$hash"
done

echo "    // ── paste the entries above into pinned() in src/transcription/verify.rs ──"
